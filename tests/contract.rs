//! The contract with jayos, regenerated and compared.
//!
//! `contract/` is what jayos vendors to test its side against this one: the
//! state document its Headphones page reads, every key that document can
//! carry, the command language the page sends, and the model prefixes its
//! Devices page matches on before this package is installed. Each file is
//! GENERATED from the code it describes, and this suite regenerates it and
//! fails on any difference -- the way jayos's `ts/build.mjs --check` holds its
//! generated JavaScript. A contract written by hand would be a second
//! description of the code, and the two would drift.
//!
//! When a change is intended, regenerate and commit the result:
//!
//!     SONY_CONTRACT_WRITE=1 cargo test --test contract
//!
//! and then re-vendor `contract/` into jayos, whose suites say which commit
//! they were checked against.

use sony_xm5::mdr::{frame, DataType};
use sony_xm5::sony::command::{self, Command, GRAMMAR};
use sony_xm5::sony::{replay, state, DAEMON_VERSION, SONY_PREFIXES};
use std::collections::BTreeSet;
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn corpus_document() -> String {
    let frames = replay::received_frames(&root().join("tests/fixtures/mdr")).expect("the corpus reads");
    replay::document(&frames, "WF-1000XM5", DAEMON_VERSION)
}

/// The corpus again, then ONE SYNTHETIC FRAME: `99 00 07 01`, the headset
/// asking DISCONNECT_CAUSED_BY_CHANGING_MULTIPOINT as a yes/no question.
///
/// Synthetic because no capture holds an alert -- the headset asked nothing
/// while the corpus was recorded (`payload::decode_alert` says why that, and
/// not alerts being off, is the likely reason) -- and here because `alert` is
/// the one key whose children
/// exist only while a question is pending. Without a document that carries
/// them, keys.txt could not list `alert.message_type`, and jayos's page could
/// not read a field the contract does not promise. The bytes are the
/// header's layout (`AlertNotifyParamFixedMessage`, T1:2080) and nothing more.
fn alert_document() -> String {
    let mut frames = replay::received_frames(&root().join("tests/fixtures/mdr")).expect("the corpus reads");
    frames.push(frame::pack(DataType::DataMdr, 0, &[0x99, 0x00, 0x07, 0x01]));
    replay::document(&frames, "WF-1000XM5", DAEMON_VERSION)
}

/// Every key path in a JSON value: `a.b`, with `[]` for an array's elements.
fn key_paths(value: &serde_json::Value, prefix: &str, out: &mut BTreeSet<String>) {
    match value {
        serde_json::Value::Object(map) => {
            for (key, child) in map {
                let path = if prefix.is_empty() { key.clone() } else { format!("{prefix}.{key}") };
                out.insert(path.clone());
                key_paths(child, &path, out);
            }
        }
        serde_json::Value::Array(items) => {
            for item in items {
                key_paths(item, &format!("{prefix}[]"), out);
            }
        }
        _ => {}
    }
}

const HEADER_KEYS: &str = "\
# Every key path the state document can carry: `a.b`, with `[]` for the
# elements of an array. Generated by tests/contract.rs from the two documents
# beside it -- the corpus replayed, and the same with one synthetic alert
# pending -- so `alert`'s children, which exist only while a question is
# waiting, are here too; do not edit. A reader may rely on any path here and
# on no path that is not.
";

const HEADER_COMMANDS: &str = "\
# The command language qs-sonyd accepts on its socket, one form per line.
# Generated by tests/contract.rs from sony::command::GRAMMAR, whose every
# example the same test parses; do not edit.
";

const HEADER_PREFIXES: &str = "\
# Device-name fragments that mark a Sony headset this package can talk to,
# matched case-insensitively anywhere in the name, as `qs-sony devices` does.
# Generated by tests/contract.rs from sony::SONY_PREFIXES; do not edit.
";

/// Every generated file, as it should be.
fn expected() -> Vec<(&'static str, String)> {
    let document = corpus_document();
    let alert = alert_document();
    let mut keys = BTreeSet::new();
    for d in [&document, &alert] {
        let value: serde_json::Value = serde_json::from_str(d).expect("the document is JSON");
        key_paths(&value, "", &mut keys);
    }

    let mut key_text = HEADER_KEYS.to_string();
    for key in &keys {
        key_text.push_str(key);
        key_text.push('\n');
    }

    let mut command_text = HEADER_COMMANDS.to_string();
    for form in GRAMMAR {
        command_text.push_str(form.form);
        command_text.push('\n');
    }

    let mut prefix_text = HEADER_PREFIXES.to_string();
    for prefix in SONY_PREFIXES {
        prefix_text.push_str(prefix);
        prefix_text.push('\n');
    }

    vec![
        ("VERSION", format!("{}\n", state::SCHEMA_VERSION)),
        ("state.example.json", document),
        ("state.alert.example.json", alert),
        ("keys.txt", key_text),
        ("commands.txt", command_text),
        ("sony-prefixes.txt", prefix_text),
    ]
}

#[test]
fn the_contract_is_what_the_code_produces() {
    let dir = root().join("contract");
    let write = std::env::var_os("SONY_CONTRACT_WRITE").is_some_and(|v| !v.is_empty());
    let mut stale = Vec::new();
    for (name, want) in expected() {
        let path = dir.join(name);
        if write {
            std::fs::create_dir_all(&dir).expect("the contract directory");
            std::fs::write(&path, &want).expect("the contract file writes");
            continue;
        }
        match std::fs::read_to_string(&path) {
            Ok(have) if have == want => {}
            Ok(_) => stale.push(format!("{name} differs from what the code produces")),
            Err(e) => stale.push(format!("{name}: {e}")),
        }
    }
    assert!(
        stale.is_empty(),
        "contract/ is stale -- regenerate with SONY_CONTRACT_WRITE=1 cargo test --test contract, \
         commit it, and re-vendor it into jayos:\n  {}",
        stale.join("\n  ")
    );
}

#[test]
fn replaying_twice_gives_the_same_document() {
    // The contract is compared byte for byte, so a document that depended on
    // when it was replayed would fail for no change at all.
    assert_eq!(corpus_document(), corpus_document());
}

#[test]
fn transmitted_frames_are_not_replayed_as_received() {
    // A capture qs-sonyd records holds both directions. Its own questions fed
    // back as the headset's would be read as answers.
    let dir = std::env::temp_dir().join(format!("sony-contract-tx-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("a scratch directory");
    let corpus = root().join("tests/fixtures/mdr");
    let first = std::fs::read_dir(&corpus)
        .expect("the corpus")
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".bin"))
        .min()
        .expect("a frame");
    std::fs::copy(corpus.join(&first), dir.join(first.replace("-rx.", "-tx."))).expect("a tx copy");
    assert!(replay::received_frames(&dir).expect("it reads").is_empty());
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn every_example_in_the_grammar_parses() {
    for form in GRAMMAR {
        assert!(!form.examples.is_empty(), "{} has no example to hold it to the parser", form.form);
        for line in form.examples {
            let words: Vec<&str> = line.split_ascii_whitespace().collect();
            assert!(
                command::parse_words(&words).is_ok(),
                "{line:?}, an example of {:?}, does not parse",
                form.form
            );
            assert!(
                line.starts_with(form.form.split(' ').next().expect("a verb")),
                "{line:?} is filed under {:?}, a different verb",
                form.form
            );
        }
    }
}

#[test]
fn every_command_the_parser_has_is_in_the_grammar() {
    // By variant, so a verb added to the parser and forgotten here fails --
    // the match below stops compiling when a variant is added, which is the
    // point: whoever adds one is sent here.
    let mut reached = BTreeSet::new();
    for form in GRAMMAR {
        for line in form.examples {
            let words: Vec<&str> = line.split_ascii_whitespace().collect();
            let name = match command::parse_words(&words).expect("it parses") {
                Command::Status => "status",
                Command::PanelOpen => "panel-open",
                Command::PanelClose => "panel-close",
                Command::Refresh => "refresh",
                Command::Noise(_) => "noise",
                Command::AmbientLevel(_) => "ambient-level",
                Command::FocusOnVoice(_) => "focus-on-voice",
                Command::SpeakToChat(_) => "speak-to-chat",
                Command::Dsee(_) => "dsee",
                Command::EqualizerPreset(_) => "eq-preset",
                Command::EqBand { .. } => "eq-band",
                Command::ClearBass(_) => "clear-bass",
                Command::GeneralSetting { .. } => "general",
                Command::ConnectionPriority(_) => "connection",
                Command::Volume(_) => "volume",
                Command::Playback(_) => "playback",
                Command::Alert(_) => "alert",
            };
            reached.insert(name);
        }
    }
    assert_eq!(reached.len(), 17, "a Command variant has no example in GRAMMAR: reached {reached:?}");
}

#[test]
fn the_help_text_is_the_grammar() {
    let mut want = String::from("commands:\n");
    for form in GRAMMAR {
        want.push_str("  ");
        want.push_str(form.form);
        want.push('\n');
    }
    assert_eq!(command::usage(), want, "usage() and GRAMMAR say different things");
}

#[test]
fn every_key_path_is_carried_by_the_document_it_was_generated_from() {
    // The other direction from `the_contract_is_what_the_code_produces`: a key
    // listed in keys.txt that no document carries would be a promise to a
    // reader that nothing keeps.
    let keys_file = std::fs::read_to_string(root().join("contract/keys.txt")).expect("keys.txt");
    let mut present = BTreeSet::new();
    for d in [corpus_document(), alert_document()] {
        let value: serde_json::Value = serde_json::from_str(&d).expect("the document is JSON");
        key_paths(&value, "", &mut present);
    }
    for line in keys_file.lines().filter(|l| !l.starts_with('#') && !l.is_empty()) {
        assert!(present.contains(line), "keys.txt promises {line}, which no document carries");
    }
}
